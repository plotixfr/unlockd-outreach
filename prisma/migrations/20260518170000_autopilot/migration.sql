ALTER TABLE "Prospect" ADD COLUMN IF NOT EXISTS "autoGenerated" BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE "Prospect" ADD COLUMN IF NOT EXISTS "autoScheduled" BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE "Prospect" ADD COLUMN IF NOT EXISTS "briefId"       TEXT;

CREATE INDEX IF NOT EXISTS "Prospect_source_idx"     ON "Prospect"("source");
CREATE INDEX IF NOT EXISTS "Prospect_externalId_idx" ON "Prospect"("externalId");
CREATE INDEX IF NOT EXISTS "Prospect_briefId_idx"    ON "Prospect"("briefId");
CREATE INDEX IF NOT EXISTS "DiscoveryRun_briefId_idx" ON "DiscoveryRun"("briefId");
CREATE INDEX IF NOT EXISTS "SearchBrief_active_idx"  ON "SearchBrief"("active");

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'Prospect_briefId_fkey') THEN
        ALTER TABLE "Prospect" ADD CONSTRAINT "Prospect_briefId_fkey"
            FOREIGN KEY ("briefId") REFERENCES "SearchBrief"("id") ON DELETE SET NULL;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'DiscoveryRun_briefId_fkey') THEN
